<h2>Frequently Asked Questions</h2>

<h3>What's the difference between a HydraFacial and a regular facial?</h3>
<p>A regular facial is manual — an aesthetician cleanses, extracts by hand, and applies products. A HydraFacial is delivered by a device that does the same three steps but with more consistency, more suction-based extraction (which is gentler on skin than pinching), and instant hydration during the extraction phase itself.</p>

<h3>Does a HydraFacial hurt?</h3>
<p>No. It's genuinely comfortable — the suction sensation is more of a gentle tugging than anything painful. Some clients find it relaxing enough to almost fall asleep.</p>

<h3>How long does the glow last?</h3>
<p>Immediate glow lasts about 5 to 7 days on average. Monthly treatments extend that to a near-continuous glow.</p>

<h3>Can I wear makeup right after?</h3>
<p>Yes. You can apply makeup within an hour of treatment. Most clients get a HydraFacial on their lunch break and head back to work with visibly better skin.</p>

<h3>Is HydraFacial safe during pregnancy?</h3>
<p>Generally yes — the treatment itself is mechanical, not chemical. But we usually skip the salicylic acid step and any add-on serums that contain retinol or peptides during pregnancy. Talk to us at consultation.</p>

<h3>Can I do a HydraFacial in the same day as Botox or filler?</h3>
<p>We recommend waiting 2 weeks between injectables and HydraFacial in either direction. The suction and pressure during the facial can theoretically shift filler placement, and Botox needs time to fully take effect before you introduce any topical intensive treatment.</p>

<h3>How is HydraFacial different from Microneedling?</h3>
<p>HydraFacial works on the surface — extraction, hydration, brightening. Microneedling creates controlled micro-injuries to trigger deeper collagen production and works on wrinkles, scars, and skin texture at a deeper level. They complement each other; many clients rotate between them.</p>

<h3>Is HydraFacial worth it if I already have a good skincare routine?</h3>
<p>Honestly, yes — because a great home routine can't replicate the extraction step. Even the best cleansers and exfoliants don't get into pores the way HydraFacial's vortex suction does. Think of it as monthly maintenance that lets your daily routine work better.</p>
