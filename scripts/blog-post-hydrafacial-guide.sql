<h2>What a HydraFacial Actually Is</h2>

<p>A HydraFacial isn't a facial in the traditional sense. No steam room, no essential-oil aromatherapy, no extended massage. The treatment is delivered by a machine — specifically the HydraFacial Syndeo — that uses a patented Vortex-Fusion tip to do three things simultaneously:</p>

<ol>
  <li>Cleanse and gently exfoliate the top layer of skin</li>
