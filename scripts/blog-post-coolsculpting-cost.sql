<p>The most common question: does it hurt?</p>

<p>Not really. The applicator suctions the treatment area, which feels like a strong pinch for the first five minutes. Then the area goes numb from the cold and you feel nothing for the rest of the 35 to 45 minutes. Most clients bring a laptop and work through the session.</p>

