<h3>What's the best laser for melasma?</h3>
<p>Picosecond lasers like the Candela PicoWay are considered the best laser option for melasma because they target pigment without the thermal damage that causes older lasers to worsen the condition. Even PicoWay works best as part of a combined protocol with topicals and sun protection, not on its own.</p>

<h3>Can melasma be cured permanently?</h3>
<p>No. Melasma is a chronic condition — it can be significantly cleared and controlled with the right protocol, but it will typically return without ongoing maintenance. Most clients achieve 70–90% clearance with consistent treatment and can maintain those results long-term with the right routine.</p>

<h3>Why did my melasma get worse after IPL?</h3>
<p>Because IPL uses broad-spectrum heat. Melasma-prone melanocytes respond to any inflammation by producing more pigment — so heat-based treatments often cause rebound hyperpigmentation. This is the single most common reason we see clients whose melasma is significantly worse than when they started treatment elsewhere.</p>

<h3>Does hydroquinone actually work for melasma?</h3>
<p>Yes, hydroquinone is one of the most effective topical treatments for melasma — but it needs to be cycled (not used continuously) to prevent tolerance and ochronosis. We prescribe it as part of a rotating protocol with other agents like tretinoin, kojic acid, and tranexamic acid.</p>

