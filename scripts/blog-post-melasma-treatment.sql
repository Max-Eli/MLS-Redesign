<h2>What Melasma Is (And Why It's Hard)</h2>

<p>Melasma is a chronic pigmentation condition — usually appearing as symmetric brown or gray-brown patches on the cheeks, forehead, upper lip, or chin. It's triggered by a combination of hormones (estrogen and progesterone, which is why it commonly shows up during pregnancy or on birth control), sun exposure, and heat.</p>

<p>Here's the frustrating part: the melanocytes (pigment-producing cells) in melasma-affected skin are hyperactive and responsive to inflammation. That means <strong>any treatment that causes inflammation can make melasma darker instead of lighter.</strong></p>

<p>That includes:</p>

<ul>
  <li>Heat-based lasers (IPL, older Q-switched systems, most fractional lasers)</li>
