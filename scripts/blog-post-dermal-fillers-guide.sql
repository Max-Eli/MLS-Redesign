<p>Dermal fillers have gone from niche cosmetic procedure to something almost every adult in Miami has either done, considered, or knows five people who've had done. That mainstream adoption has produced two side effects: prices have wildly diverged (from $299 Groupons to $2,000 injector-picks) and the results people are getting have wildly diverged too. Same product, same face, radically different outcomes.</p>

